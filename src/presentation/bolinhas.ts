/** A bolinha de um personagem (a da tabela, ou o relógio do motor / acesa com a estrelinha). */
export const bolinhaDe = (id: string): Bolinha => BOLINHAS[id] ?? { ic: Sparkles };

/**
 * A cor da bolinha: a mesma do efeito que a mecânica solta ao ativar (o anel, o brilho e o fundo puxam essa cor),
 * para a bolinha "avisar" com a cara do que vem. Sem efeito próprio, a cor do personagem; a cor da tabela vence.
 */
const coresDaBolinha = new Map<string, string>();
export function corDaBolinha(id: string): string | undefined {
  if (BOLINHAS[id]?.cor) return BOLINHAS[id].cor;
  if (coresDaBolinha.has(id)) return coresDaBolinha.get(id);
  const c = byId[id], efeito = Object.values(EFEITO_DA_UNICA[id] ?? {})[0];
  const cor = !c ? undefined : efeito ? corDoEfeito(efeito.familia, c, 'unica', unicaDe(id)?.nome ?? '') : legivel(c.color);
  coresDaBolinha.set(id, cor ?? '');
  return cor;
}
