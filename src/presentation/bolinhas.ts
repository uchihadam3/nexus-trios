type F = Fighter;
type B = Battle;
const rivais = (f: F, b: B) => b.fighters.filter((x) => x.side !== f.side && x.hp > 0);
const aliados = (f: F, b: B) => b.fighters.filter((x) => x.side === f.side && x.hp > 0);
const tem = (x: F, s: StatusId) => x.statuses.some((y) => y.id === s);
const fr = (x: F) => (x.maxHp ? x.hp / x.maxHp : 0);
const algumRival = (s: StatusId) => (f: F, b: B) => rivais(f, b).some((x) => tem(x, s));
const vidaDoTrio = (xs: F[]) => xs.reduce((t, x) => t + Math.max(0, x.hp), 0) / Math.max(1, xs.reduce((t, x) => t + x.maxHp, 0));
const ate = (k: string) => (f: F, b: B) => (f.u?.[k] ?? 0) > b.time;

const rel = (ic: LucideIcon, x: Partial<Bolinha> = {}): Bolinha => ({ ic, modo: 'relogio', ...x });
const ace = (ic: LucideIcon): Bolinha => ({ ic, modo: 'acesa' });
const liga = (ic: LucideIcon, vale: (f: F, b: B) => boolean): Bolinha => ({ ic, modo: 'liga', vale });
const vez = (ic: LucideIcon, usada: string): Bolinha => ({ ic, modo: 'vez', usada });
const vida = (ic: LucideIcon, lim: number[], usada?: string): Bolinha => ({ ic, modo: 'vida', lim, usada });
const sorte = (ic: LucideIcon, p: number): Bolinha => ({ ic, modo: 'chance', p });
const ciclo = (ic: LucideIcon, k: string, n: number): Bolinha => ({ ic, modo: 'ciclo', k, n });
const conta = (ic: LucideIcon, k: string, max: number): Bolinha => ({ ic, modo: 'conta', k, max });
const pilhas = (ic: LucideIcon, k: string, max: number): Bolinha => ({ ic, modo: 'pilhas', k, max });
const barra = (ic: LucideIcon, k: string, max: number): Bolinha => ({ ic, modo: 'barra', k, max });
const tempo = (ic: LucideIcon, em: number, usada?: string): Bolinha => ({ ic, modo: 'tempo', em, usada });
/** "No máximo 1 vez a cada X s": enche enquanto recarrega e mostra os segundos; pronta, acende. */
const recarga = (ic: LucideIcon, k: string, dur: number): Bolinha => ({
  ic, modo: 'vez',
  valor: (f, b) => 1 - Math.max(0, (f.u?.[k] ?? 0) - b.time) / dur,
  texto: (f, b) => { const r = (f.u?.[k] ?? 0) - b.time; return r > 0 ? `${Math.ceil(r)}` : undefined; },
});
/** Quantos rivais caíram até agora (as mecânicas que crescem a cada queda). */
const caidos = (f: F, b: B) => b.fighters.filter((x) => x.side !== f.side && x.hp <= 0).length;

