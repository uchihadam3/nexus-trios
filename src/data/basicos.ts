/** Põe o nome e o jeito de bater na ficha do personagem. */
export const aplicaBasico = (c: Character): Character => {
  const b = BASICOS[c.id];
  if (!b) return c;
  const [name, jeito] = b;
  return { ...c, basic: { ...c.basic, name, ...(jeito ? { jeito } : {}) } };
};
