import type { Character, JeitoDeBater, StatusId } from '../engine/types';

/*
 * O ataque básico de cada um, com nome e jeito próprios.
 *
 * Pedido do jogador: "o ataque básico também… individualidade pros
 * personagens". Os 250 se chamavam "Ataque básico" e 147 só davam dano. Agora
 * cada um bate do jeito do personagem: o Capitão arremessa o escudo que quica
 * no segundo rival, o Hulk varre dois, a Sakura cura com o chakra do soco, o
 * Kakashi copia (rouba Carga), o Flash fica mais rápido a cada golpe, o
 * Naruto fecha o combo no 3º golpe. Quem já tinha um efeito no básico
 * (Queimadura, investigação, Escudo…) só ganha o nome.
 *
 * O tamanho de cada jeito é pequeno de propósito: a força de todos é medida
 * de novo no fim (scripts/medir-forca) e o equilíbrio acerta o resto.
 */
